let isTranslating = false;
let mutationObserver = null;

export function getCurrentLanguage() {
  if (typeof window === 'undefined') return 'fr';
  return localStorage.getItem('prime_language') || 'fr';
}

/**
 * Translates the visible DOM text nodes, placeholders, options and title
 */
export function translateDom(isAr) {
  if (typeof document === 'undefined') return;
  if (isTranslating) return;
  isTranslating = true;

  try {
    // 1. Text nodes
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
      {
        acceptNode(node) {
          const parent = node.parentElement;
          if (!parent) return NodeFilter.FILTER_REJECT;
          const tag = parent.tagName.toLowerCase();
          if (['script', 'style', 'textarea', 'svg', 'noscript', 'code'].includes(tag)) {
            return NodeFilter.FILTER_REJECT;
          }
          if (
            parent.classList.contains('material-symbols-outlined') ||
            parent.classList.contains('material-symbols') ||
            parent.classList.contains('no-translate')
          ) {
            return NodeFilter.FILTER_REJECT;
          }
          const text = node.nodeValue.trim();
          if (!text) return NodeFilter.FILTER_REJECT;
          return NodeFilter.FILTER_ACCEPT;
        }
      }
    );

    const textNodes = [];
    let curr;
    while ((curr = walker.nextNode())) {
      textNodes.push(curr);
    }

    textNodes.forEach(node => {
      const raw = node.nodeValue;
      const trimmed = raw.trim();

      if (isAr) {
        if (I18N_DICT[trimmed]) {
          if (typeof node._origText === 'undefined') {
            node._origText = raw;
          }
          node.nodeValue = raw.replace(trimmed, I18N_DICT[trimmed]);
        }
      } else {
        if (typeof node._origText !== 'undefined') {
          node.nodeValue = node._origText;
          delete node._origText;
        }
      }
    });

    // 2. Select Option elements
    document.querySelectorAll('select option').forEach(opt => {
      const optText = opt.textContent.trim();
      if (isAr) {
        if (I18N_DICT[optText]) {
          if (!opt.dataset.origText) opt.dataset.origText = optText;
          opt.textContent = I18N_DICT[optText];
        }
      } else {
        if (opt.dataset.origText) {
          opt.textContent = opt.dataset.origText;
          delete opt.dataset.origText;
        }
      }
    });

    // 3. Inputs & Textareas Placeholders
    document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(input => {
      const ph = input.getAttribute('placeholder');
      if (!ph) return;
      if (isAr) {
        if (I18N_DICT[ph]) {
          if (!input.dataset.origPlaceholder) input.dataset.origPlaceholder = ph;
          input.setAttribute('placeholder', I18N_DICT[ph]);
        }
      } else {
        if (input.dataset.origPlaceholder) {
          input.setAttribute('placeholder', input.dataset.origPlaceholder);
          delete input.dataset.origPlaceholder;
        }
      }
    });

    // 4. Document Title
    if (isAr) {
      if (!document._origTitle) document._origTitle = document.title;
      if (I18N_DICT[document.title]) {
        document.title = I18N_DICT[document.title];
      } else if (document.title.includes('Prime House')) {
        document.title = document.title.replace('Prime House', 'برايم هاوس');
      }
    } else {
      if (document._origTitle) {
        document.title = document._origTitle;
        delete document._origTitle;
      }
    }
  } finally {
    isTranslating = false;
  }
}

/**
 * Switch & apply language system-wide
 */
export function applyLanguage(lang, notify = false) {
  if (typeof window === 'undefined') return;

  const isAr = lang === 'ar';
  document.documentElement.setAttribute('dir', isAr ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', isAr ? 'ar' : 'fr');
  localStorage.setItem('prime_language', lang);

  // Run DOM translation
  translateDom(isAr);

  // Setup / teardown observer for dynamic re-renders
  if (isAr) {
    startObserver();
  } else {
    stopObserver();
  }

  // Notify listeners
  window.dispatchEvent(new CustomEvent('prime:language-changed', { detail: { lang } }));

  if (notify && typeof window.showToast === 'function') {
    window.showToast(isAr ? 'تم تفعيل الواجهة باللغة العربية بنجاح' : 'Langue française sélectionnée', 'info');
  }
}

let debounceTimer = null;
function startObserver() {
  if (typeof document === 'undefined' || mutationObserver) return;
  mutationObserver = new MutationObserver(() => {
    if (isTranslating) return;
    clearTimeout(debounceTimer);
    debounceTimer = setTimeout(() => {
      translateDom(true);
    }, 80);
  });

  mutationObserver.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true
  });
}

function stopObserver() {
  if (mutationObserver) {
    mutationObserver.disconnect();
    mutationObserver = null;
  }
}

if (typeof window !== 'undefined') {
  window.applyLanguage = applyLanguage;
  window.PrimeI18n = {
    dict: I18N_DICT,
    applyLanguage,
    translateDom,
    getCurrentLanguage
  };
}
